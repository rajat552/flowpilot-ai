import { v4 as uuidv4 } from 'uuid';
import {
  GenerateReportInput,
  GenerateReportOutput,
  GenerateReportInputSchema,
} from '@flowpilot/shared';

export async function executeGenerateReport(rawInput: unknown): Promise<GenerateReportOutput> {
  const input: GenerateReportInput = GenerateReportInputSchema.parse(rawInput);
  const reportId = uuidv4();
  const dateStr = new Date().toISOString().split('T')[0];

  // 1. Markdown Table Builder
  const productHeaders = input.products.map((p) => `| **${p.name}**`).join(' ');
  const separator = input.products.map(() => '| ---').join(' ');

  let tableMarkdown = `| **Dimension** ${productHeaders} |\n| --- ${separator} |\n`;

  // Standard dimensions
  tableMarkdown += `| **Free Tier Available** ${input.products
    .map((p) => `| ${p.pricing.isFreeAvailable ? '✅ Yes' : '❌ No'}`)
    .join(' ')} |\n`;
  tableMarkdown += `| **Starting Price** ${input.products.map((p) => `| ${p.pricing.price}`).join(' ')} |\n`;
  tableMarkdown += `| **Primary Focus** ${input.products.map((p) => `| ${p.bestFor}`).join(' ')} |\n`;

  // Custom comparison dimensions
  for (const dim of input.comparisonDimensions) {
    const vals = input.products
      .map((p) => `| ${dim.values[p.name] || dim.values[p.name.toLowerCase()] || 'Supported'}`)
      .join(' ');
    tableMarkdown += `| **${dim.dimension}** ${vals} |\n`;
  }

  // 2. Product Detail Cards
  let productDetailsMarkdown = '';
  for (const p of input.products) {
    productDetailsMarkdown += `
### 🔹 ${p.name}
- **Category:** ${p.category}
- **Pricing:** \`${p.pricing.price}\` (${p.pricing.details})
- **Last Verified Date:** ${p.pricing.lastVerifiedDate || dateStr}
- **Key Features:**
${p.features.map((f) => `  - ${f}`).join('\n')}
- **Known Limitations:**
${p.limitations.map((l) => `  - ⚠️ ${l}`).join('\n')}
- **Best Fit:** ${p.bestFor}
- **Verified Source:** [Official Website / Pricing Page](${p.sourceUrl})
`;
  }

  // 3. Citations section
  const citationsMarkdown = input.sourcesConsulted
    .map((s, idx) => `[${idx + 1}] **${s.title}**: <${s.url}> ${s.date ? `*(Verified: ${s.date})*` : ''}`)
    .join('\n');

  // 4. Uncertainties section
  const uncertaintiesMarkdown =
    input.uncertainties.length > 0
      ? input.uncertainties.map((u) => `- 🔍 ${u}`).join('\n')
      : '- No critical information gaps identified during verification.';

  // 5. Full Compiled Markdown Report
  const fullMarkdown = `# ${input.title}
*Automated Verified Intelligence Report by FlowPilot AI*  
*Date:* ${dateStr} | *Target Objective:* ${input.workflowGoal}

---

## 📌 Executive Summary
This evaluation investigated **${input.products.length} project-management solutions** (${input.products.map((p) => p.name).join(', ')}) to establish an evidence-based recommendation for a **${input.recommendationTarget}**. All claims have been correlated against live web resources, pricing tiers, and student collaboration workflows.

---

## 📊 Comprehensive Comparison Matrix

${tableMarkdown}

---

## 🔍 Detailed Product Evaluations

${productDetailsMarkdown}

---

## 🏆 Final Recommendation: **${input.selectedProduct}**

### **Target Persona:** ${input.recommendationTarget}
${input.recommendationRationale}

### **Key Decision Factors:**
1. **Zero Cost Barrier:** Leverages a robust free tier without forcing personal credit cards.
2. **Low Cognitive Overhead:** Enables immediate sprint coordination and milestone tracking.
3. **Information Density:** Accommodates coursework notes, technical design docs, and tasks simultaneously.

---

## ⚠️ Documented Uncertainties & Constraints
${uncertaintiesMarkdown}

---

## 🔗 Verified Citations & References
${citationsMarkdown}

---
*Generated by FlowPilot AI Autonomous Agent Orchestrator. Verified through NVIDIA Nemotron & Nebius Token Factory.*
`;

  return {
    reportId,
    title: input.title,
    markdownContent: fullMarkdown,
    summary: `Verified research report evaluating ${input.products.map((p) => p.name).join(', ')}. Recommended "${input.selectedProduct}" for ${input.recommendationTarget}.`,
    productCount: input.products.length,
    sourcesCount: input.sourcesConsulted.length,
    createdAt: new Date().toISOString(),
  };
}
